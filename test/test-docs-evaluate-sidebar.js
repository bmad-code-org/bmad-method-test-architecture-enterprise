/**
 * Every Evaluate page is reachable from the site's sidebar, and the TEA overview links each page that teaches Evaluate.
 *
 * The Starlight sidebar in `website/astro.config.mjs` lists how-to, explanation and reference pages by explicit `slug:`
 * and autogenerates whole directories (the tutorials, the customization and brownfield how-tos).
 * A page the sidebar misses still builds, and no reader finds it.
 *
 * An Evaluate page is any `docs/` page whose text names `tea-evaluate` or `bmad-testarch-evaluate`, and any page whose own path names Evaluate.
 * A page whose own path names Evaluate (`how-to/evaluate/`, `tutorials/evaluate-*`, `explanation/*evaluate*`,
 * `reference/tea-evaluate-cli`) is one Evaluate owns, and the overview has to link every one of those.
 *
 * Each rule has revert cases that mutate a copy of the config text or of the overview text:
 * remove what covers one page and the check names that page.
 *
 * Usage: node test/test-docs-evaluate-sidebar.js
 */

'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const PROJECT_ROOT = path.join(__dirname, '..');
const DOCS_ROOT = path.join(PROJECT_ROOT, 'docs');
const CONFIG_FILE = path.join(PROJECT_ROOT, 'website', 'astro.config.mjs');
const OVERVIEW_PAGE = 'explanation/tea-overview';

/** What makes a page an Evaluate page. */
const EVALUATE_NAMES = /\btea-evaluate\b|\bbmad-testarch-evaluate\b/;

/** What makes an Evaluate page one that Evaluate owns: its own path says so, and that alone makes it an Evaluate page. */
const OWNED_PATH = /evaluate/;

/** The slug Starlight gives a page: its path without `.md`, and a directory's `index` is the directory. */
function slugOf(relativePath) {
  const slug = relativePath.split(path.sep).join('/').replace(/\.md$/, '');
  if (slug === 'index') return 'index';
  return slug.replace(/\/index$/, '');
}

/** Every docs page as `{ slug, text }`, sorted by slug. */
function readPages(root = DOCS_ROOT) {
  const pages = [];
  const visit = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) visit(full);
      else if (entry.name.endsWith('.md')) pages.push({ slug: slugOf(path.relative(root, full)), text: fs.readFileSync(full, 'utf8') });
    }
  };
  visit(root);
  return pages.sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));
}

/** The slugs of the pages that name Evaluate. */
function evaluateSlugs(pages) {
  return pages.filter(({ slug, text }) => OWNED_PATH.test(slug) || EVALUATE_NAMES.test(text)).map(({ slug }) => slug);
}

/** The slugs of the Evaluate pages Evaluate owns, which the overview must link. */
function ownedSlugs(pages) {
  return evaluateSlugs(pages).filter((slug) => OWNED_PATH.test(slug));
}

/** The config text without its whole-line `//` comments. */
function withoutComments(configText) {
  return configText
    .split('\n')
    .filter((line) => !/^\s*\/\//.test(line))
    .join('\n');
}

/** The explicit `slug:` entries, in the order the config lists them. */
function explicitSlugs(configText) {
  return [...withoutComments(configText).matchAll(/\bslug:\s*(['"])([^'"]+)\1/g)].map((match) => match[2]);
}

/** The `autogenerate: { directory }` entries. */
function autogeneratedDirectories(configText) {
  return [...withoutComments(configText).matchAll(/\bautogenerate:\s*\{\s*directory:\s*(['"])([^'"]+)\1/g)].map((match) => match[2]);
}

/** Whether the sidebar reaches a slug, by explicit entry or by an autogenerated directory above it. */
function reaches(configText, slug) {
  if (explicitSlugs(configText).includes(slug)) return true;
  return autogeneratedDirectories(configText).some((directory) => slug.startsWith(`${directory.replace(/\/$/, '')}/`));
}

/** One problem per page the sidebar misses, and per explicit entry that names no page. */
function sidebarProblems(configText, slugs, allSlugs) {
  const problems = [];
  for (const slug of slugs) {
    if (!reaches(configText, slug)) problems.push(`${slug} is an Evaluate page and the sidebar does not reach it`);
  }
  for (const slug of explicitSlugs(configText)) {
    if (!allSlugs.includes(slug)) problems.push(`the sidebar lists ${slug}, which is no page under docs/`);
  }
  return problems;
}

/** The slugs a page's Markdown links resolve to, for links that stay inside `docs/`. */
function linkedSlugs(pageSlug, text) {
  const linked = new Set();
  for (const match of text.matchAll(/\]\(([^)\s#]+)(?:#[^)\s]*)?\)/g)) {
    const target = match[1];
    if (/^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
    let resolved;
    if (target.startsWith('/docs/')) resolved = target.slice('/docs/'.length);
    else if (target.startsWith('/')) resolved = target.slice(1);
    else resolved = path.posix.join(path.posix.dirname(`${pageSlug}.md`), target);
    resolved = path.posix.normalize(resolved).replace(/\.md$/, '').replace(/\/$/, '');
    linked.add(resolved.replace(/\/index$/, ''));
  }
  return linked;
}

/** One problem per owned Evaluate page the overview does not link. */
function overviewProblems(overviewText, owned) {
  const linked = linkedSlugs(OVERVIEW_PAGE, overviewText);
  return owned.filter((slug) => !linked.has(slug)).map((slug) => `${OVERVIEW_PAGE} does not link ${slug}`);
}

/** `text` with every Markdown link to `slug` from `fromSlug` turned into plain text. */
function withoutLinksTo(fromSlug, slug, text) {
  return text.replaceAll(/\[([^\]]*)\]\(([^)\s]+)\)/g, (whole, label, target) =>
    linkedSlugs(fromSlug, `](${target})`).has(slug) ? label : whole,
  );
}

/** `text` as a regular expression source that matches it literally. */
function literal(text) {
  return text.replaceAll(/[.*+?^${}()|[\]\\]/g, String.raw`\$&`);
}

/** The config text with everything that reaches `slug` removed: its explicit entries and the directories above it. */
function withoutCoverage(configText, slug) {
  let mutated = configText;
  const explicit = new RegExp(`^.*\\bslug:\\s*(['"])${literal(slug)}\\1.*\\n?`, 'gm');
  mutated = mutated.replaceAll(explicit, '');
  for (const directory of autogeneratedDirectories(configText)) {
    if (slug.startsWith(`${directory.replace(/\/$/, '')}/`)) {
      const entry = new RegExp(`^.*\\bautogenerate:\\s*\\{\\s*directory:\\s*(['"])${literal(directory)}\\1\\s*\\}.*\\n?`, 'gm');
      mutated = mutated.replaceAll(entry, '');
    }
  }
  return mutated;
}

/** The revert cases: every rule fails on a mutated copy and passes on the original. */
function revertCaseProblems(configText, overviewText, pages) {
  const failures = [];
  const slugs = evaluateSlugs(pages);
  const allSlugs = pages.map(({ slug }) => slug);
  const owned = ownedSlugs(pages);
  for (const slug of slugs) {
    const mutated = withoutCoverage(configText, slug);
    if (mutated === configText) {
      failures.push(`removing the sidebar coverage of ${slug} changed nothing`);
      continue;
    }
    if (!sidebarProblems(mutated, slugs, allSlugs).some((problem) => problem.startsWith(`${slug} `))) {
      failures.push(`the sidebar check passed with the coverage of ${slug} removed`);
    }
  }
  for (const slug of owned) {
    const mutated = withoutLinksTo(OVERVIEW_PAGE, slug, overviewText);
    if (mutated === overviewText) {
      failures.push(`removing the overview's link to ${slug} changed nothing`);
      continue;
    }
    if (!overviewProblems(mutated, owned).some((problem) => problem.endsWith(` ${slug}`))) {
      failures.push(`the overview check passed with its link to ${slug} removed`);
    }
  }
  const nameless = [{ slug: 'how-to/evaluate/a-page-that-names-no-command', text: '# A page about checking results\n' }];
  if (!evaluateSlugs(nameless).includes(nameless[0].slug) || !ownedSlugs(nameless).includes(nameless[0].slug)) {
    failures.push('a page under how-to/evaluate/ that names neither tea-evaluate nor bmad-testarch-evaluate escaped the Evaluate pages');
  }
  const bystander = [{ slug: 'how-to/workflows/a-page-about-something-else', text: '# Something else\n' }];
  if (evaluateSlugs(bystander).length > 0) failures.push('a page that names Evaluate nowhere counted as an Evaluate page');
  const newPage = 'how-to/evaluate/a-page-nobody-listed';
  if (!sidebarProblems(configText, [...slugs, newPage], [...allSlugs, newPage]).some((problem) => problem.startsWith(`${newPage} `))) {
    failures.push('a new Evaluate page the sidebar does not list passed the sidebar check');
  }
  const deadEntry = configText.replace(/(\bslug:\s*)(['"])explanation\/tea-overview\2/, '$1$2explanation/no-such-page$2');
  if (!sidebarProblems(deadEntry, [], allSlugs).some((problem) => problem.includes('explanation/no-such-page'))) {
    failures.push('a sidebar entry that names no page passed the sidebar check');
  }
  const unlinkedNewPage = [...owned, 'how-to/evaluate/a-page-nobody-listed'];
  if (!overviewProblems(overviewText, unlinkedNewPage).some((problem) => problem.endsWith(' how-to/evaluate/a-page-nobody-listed'))) {
    failures.push('a new owned Evaluate page the overview does not link passed the overview check');
  }
  return failures;
}

function main() {
  const configText = fs.readFileSync(CONFIG_FILE, 'utf8');
  const pages = readPages();
  const overview = pages.find(({ slug }) => slug === OVERVIEW_PAGE);
  const slugs = evaluateSlugs(pages);
  const owned = ownedSlugs(pages);
  const failures = [];
  try {
    assert.ok(overview, `${OVERVIEW_PAGE} is no page under docs/`);
    assert.ok(slugs.includes('reference/tea-evaluate-cli'), 'the scan misses reference/tea-evaluate-cli');
    assert.ok(owned.includes('reference/tea-evaluate-cli'), 'the owned pages miss reference/tea-evaluate-cli');
    assert.ok(
      explicitSlugs(configText).length > 10 && autogeneratedDirectories(configText).length > 0,
      'the config parse found no sidebar entries',
    );
  } catch (error) {
    failures.push(error.message);
  }
  if (overview) {
    failures.push(...revertCaseProblems(configText, overview.text, pages), ...overviewProblems(overview.text, owned));
  }
  failures.push(
    ...sidebarProblems(
      configText,
      slugs,
      pages.map(({ slug }) => slug),
    ),
  );
  if (failures.length > 0) {
    console.error(`docs-evaluate-sidebar: ${failures.length} problem(s)`);
    for (const failure of failures) console.error(`  - ${failure}`);
    process.exit(1);
  }
  console.log(
    `docs-evaluate-sidebar: ${slugs.length} Evaluate pages sit in the sidebar, the overview links ${owned.length} of them, and each rule fails on its revert case`,
  );
}

if (require.main === module) main();

module.exports = {
  evaluateSlugs,
  ownedSlugs,
  explicitSlugs,
  autogeneratedDirectories,
  sidebarProblems,
  overviewProblems,
  linkedSlugs,
  readPages,
  revertCaseProblems,
};
